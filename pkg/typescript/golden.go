package typescript

import (
	"flag"
	"os"
	"reflect"
	"testing"
)

var update = flag.Bool("update", false, "rewrite the TypeScript the Go types declare")

func Header(command string) string {
	return "// Code generated by `" + command + "`. DO NOT EDIT."
}

func RequireDeclared(t *testing.T, path, header string, imports []Import, roots ...reflect.Type) {
	t.Helper()
	declared, err := Declare(header, imports, roots...)
	if err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(path, []byte(declared), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	written, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; regenerate it with -update", path, err)
	}
	if string(written) != declared {
		t.Errorf("%s is not what the Go types declare; regenerate it with -update. Want:\n%s", path, declared)
	}
}
