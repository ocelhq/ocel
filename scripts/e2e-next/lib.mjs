// Pure helpers shared by the Next.js adapter-harness lifecycle scripts
// (deploy.mjs, logs.mjs, cleanup.mjs, merge-baseline.mjs). The harness runs
// them as separate processes, so everything they share travels through files in
// the temp app directory rather than memory.

import { createHash } from "node:crypto";
import { join } from "node:path";

/** A valid single DNS label, per RFC 1035 (mirrors cli/internal/previewid). */
export const DNS_LABEL = /^[a-z]([a-z0-9-]{0,61}[a-z0-9])?$/;

/** The file deploy.mjs persists this app's identity to, read by logs/cleanup. */
export const STATE_FILE = ".ocel-e2e.json";

/** The file every byte of the deploy's output is redirected to. */
export const BUILD_LOG_FILE = ".adapter-build.log";

/** The CLI's machine-readable deploy result, relative to the app directory. */
export const DEPLOY_RESULT_FILE = join(".ocel", "deploy-result.json");

/** How many hex characters of the temp dir's hash disambiguate one app. */
const HASH_LEN = 8;

/** Run-id token used when the scripts run outside GitHub Actions. */
const LOCAL_RUN_ID = "local";

/**
 * The name every temp app is declared under. Isolation lives in the project slug
 * (projectSlug), so a per-app name would buy nothing and cost length: the
 * Cloudflare worker script name derived from both ("ocel-<slug>-preview-<app>")
 * has 63 characters to fit in.
 */
export const APP_NAME = "app";

/**
 * The longest slug a preview pointer named after it can still be served on: the
 * route hostname's first label is the pointer plus an 11-character suffix
 * (cloud/aws/deploy/previewhost.go) and a DNS label holds 63, which is the same
 * cap `ocel preview up --name` enforces (cli/internal/previewid).
 */
export const MAX_SLUG_LEN = 52;

/**
 * projectSlug derives the identity that isolates one temp app: the `slug` of the
 * Ocel project it deploys into, which is also the name of the persistent preview
 * pointer inside that project. A project is the unit concurrent deploys must not
 * share — it namespaces the Pulumi stacks, the deployments store, the asset
 * prefixes and the Cloudflare worker scripts and routes — so every temp app gets
 * its own.
 *
 * It must be a valid single DNS label within MAX_SLUG_LEN (it becomes the
 * preview subdomain), unique per temp app, and stable for a given run and
 * directory: cleanup re-derives it when the state file is lost, and a slug it
 * cannot re-derive is infrastructure nothing will ever tear down.
 */
export function projectSlug({ runId, dir }) {
  const run = sanitizeToken(String(runId ?? "")) || LOCAL_RUN_ID;
  const hash = createHash("sha256").update(String(dir ?? "")).digest("hex").slice(0, HASH_LEN);
  // "e2e-" gives the label its required letter start; the run token is capped
  // so run + hash can never push the slug past MAX_SLUG_LEN.
  const maxRun = MAX_SLUG_LEN - "e2e-".length - 1 - HASH_LEN;
  return `e2e-${run.slice(0, maxRun)}-${hash}`;
}

/**
 * projectSlugForApp is how deploy.mjs and cleanup.mjs derive the slug. Both must
 * derive the same one from the same environment — a drift between them means
 * cleanup tears down the wrong project, or nothing — so the environment read
 * lives here, in one place, rather than at each call site.
 */
export function projectSlugForApp(appDir) {
  return projectSlug({ runId: process.env.GITHUB_RUN_ID, dir: process.env.NEXT_TEST_DIR || appDir });
}

function sanitizeToken(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * renderOcelConfig is the ocel.config.ts written into the temp app. `slug` is
 * this app's own project (projectSlug) — that is what gives it its own worker
 * scripts and asset prefixes — and the app under it is declared explicitly
 * rather than discovered, under APP_NAME. Pure: cleanup re-renders it from the
 * same environment when a failed deploy left no config to tear down.
 * `ocel` and `@ocel/provider-aws` must resolve from the app directory —
 * the config is bundled and executed from there.
 */
export function renderOcelConfig({ slug, previewDomain }) {
  const lines = [
    `import { defineConfig } from "ocel/config";`,
    `import awsProvider from "@ocel/provider-aws";`,
    ``,
    `// Generated by scripts/e2e-next/deploy.mjs. Do not edit.`,
    `export default defineConfig({`,
    `  slug: ${JSON.stringify(slug)},`,
    `  provider: awsProvider(),`,
  ];
  if (previewDomain) {
    lines.push(`  domains: {`, `    preview: ${JSON.stringify(previewDomain)},`, `  },`);
  }
  lines.push(
    `  apps: [{ name: ${JSON.stringify(APP_NAME)}, path: ".", framework: "next" }],`,
    `});`,
    ``,
  );
  return lines.join("\n");
}

/**
 * withBuildScript returns the app's package.json with a `build` script, which
 * buildNext requires (it throws without one). An app that already declares one
 * keeps it: the fixture may build with flags of its own.
 */
export function withBuildScript(pkg) {
  if (pkg.scripts?.build) {
    return pkg;
  }
  return { ...pkg, scripts: { ...pkg.scripts, build: "next build" } };
}

/**
 * The smoke app's revalidation probe, and the window it declares. Mirrors
 * `revalidate` and the marker in smoke-app/app/isr/page.tsx — assert-isr.mjs
 * reads them from here so the page and its assertion cannot drift apart.
 */
export const ISR_ROUTE = "/isr";
export const ISR_REVALIDATE_SECONDS = 5;

/**
 * isrToken pulls the probe page's per-render token out of its html. Null when
 * the marker is absent, which means the response was not that page at all —
 * a redirect, an error page, or a build that dropped the route — and must be
 * reported as such rather than compared as a value.
 */
export function isrToken(html) {
  return /isr-token:(\d+)/.exec(String(html ?? ""))?.[1] ?? null;
}

/**
 * deployURL is the URL the harness reads from the deploy script's stdout, taken
 * from the CLI's deploy result. A successful deploy that featured no app URL is
 * a failure for our purposes: the harness has nothing to test.
 */
export function deployURL(result) {
  const url = result?.appUrls?.[0];
  if (!url) {
    throw new Error(`deploy result carries no app URL: ${JSON.stringify(result ?? null)}`);
  }
  return url;
}

/**
 * markerLines formats the three lines the harness parses out of the logs
 * script's output. A missing value is reported as the literal "undefined",
 * which is what the contract asks for — never a blank value.
 *
 * `DEPLOYMENT_ID` is the harness's own marker name, not ours: it is an external
 * contract, so it keeps that spelling while carrying Ocel's promotion id.
 * IMMUTABLE_ASSET_TOKEN is always undefined — the Ocel adapter never sets
 * `config.deploymentId`, so its assets carry no `?dpl=` token.
 */
export function markerLines({ buildId, promotionId }) {
  return [
    `BUILD_ID: ${buildId || "undefined"}`,
    `DEPLOYMENT_ID: ${promotionId || "undefined"}`,
    `IMMUTABLE_ASSET_TOKEN: undefined`,
  ];
}

/**
 * lambdaLogGroups maps a resourcegroupstaggingapi get-resources response into
 * the CloudWatch log groups of the Lambdas it found. Function names are
 * Pulumi-autonamed, so the ocel tags (cloud/aws/deploy/function.go) are the only
 * way to find them; the caller filters on `ocel:project`, this app's own slug
 * being what is unique per deploy.
 */
export function lambdaLogGroups(response) {
  return (response?.ResourceTagMappingList ?? [])
    .map((entry) => /^arn:aws:lambda:[^:]*:[^:]*:function:([^:]+)/.exec(entry?.ResourceARN ?? ""))
    .filter(Boolean)
    .map((match) => `/aws/lambda/${match[1]}`);
}

export function tail(text, maxLines) {
  const lines = text.split("\n");
  return lines.slice(Math.max(0, lines.length - maxLines)).join("\n");
}

/** Recovers the harness's test-file key from `${test.file}.results.json`. */
export function suiteFromResultsPath(resultsPath) {
  return resultsPath
    .replace(/\\/g, "/")
    .replace(/^\.\//, "")
    .replace(/\.results\.json$/, "");
}

/**
 * suiteResultFromJest reduces one suite's Jest JSON output to the baseline
 * manifest's per-suite entry. Case names are the full "ancestors > title" path,
 * which is what the harness's excludedCases matches on.
 *
 * A suite that produced no assertions at all did not merely fail — it never
 * ran (a crash while loading, a deploy the harness could not reach), which the
 * manifest records as runtimeError so the whole file is skipped rather than
 * every case in it being listed.
 */
export function suiteResultFromJest(results) {
  const passed = [];
  const failed = [];
  for (const suite of results?.testResults ?? []) {
    for (const assertion of suite?.assertionResults ?? []) {
      const name = [...(assertion.ancestorTitles ?? []), assertion.title].filter(Boolean).join(" > ");
      if (assertion.status === "passed") {
        passed.push(name);
      } else if (assertion.status === "failed") {
        failed.push(name);
      }
    }
  }
  return { passed, failed, flakey: [], runtimeError: passed.length === 0 && failed.length === 0 };
}

/**
 * buildBaselineManifest turns one group's collected Jest results files into a
 * baseline manifest fragment, keyed by test file — the legacy (unversioned)
 * NEXT_EXTERNAL_TESTS_FILTERS shape, where a listed suite's `failed` cases are
 * excluded and any newly added case is automatically included.
 */
export function buildBaselineManifest(files) {
  const manifest = {};
  for (const { path, results } of files) {
    manifest[suiteFromResultsPath(path)] = suiteResultFromJest(results);
  }
  return manifest;
}

/**
 * mergeBaselineManifest folds every group's fragment into the one manifest the
 * repo commits. Suites are disjoint across groups in a single run, but merging
 * is defined anyway — a re-run of one group must not drop the others' entries —
 * and a suite any group saw crash stays marked as a runtime error. Keys are
 * sorted so the committed baseline diffs cleanly.
 */
export function mergeBaselineManifest(manifests) {
  const merged = {};
  for (const manifest of manifests) {
    for (const [suite, entry] of Object.entries(manifest ?? {})) {
      const prior = merged[suite];
      if (!prior) {
        merged[suite] = {
          passed: [...(entry.passed ?? [])],
          failed: [...(entry.failed ?? [])],
          flakey: [...(entry.flakey ?? [])],
          runtimeError: Boolean(entry.runtimeError),
        };
        continue;
      }
      merged[suite] = {
        passed: union(prior.passed, entry.passed),
        failed: union(prior.failed, entry.failed),
        flakey: union(prior.flakey, entry.flakey),
        runtimeError: prior.runtimeError || Boolean(entry.runtimeError),
      };
    }
  }
  return Object.fromEntries(Object.keys(merged).sort().map((suite) => [suite, merged[suite]]));
}

function union(a, b) {
  return [...new Set([...(a ?? []), ...(b ?? [])])];
}
