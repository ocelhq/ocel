describe("DNS_LABEL", () => {
  it("accepts a single valid label and rejects what is not one", () => {
    expect(DNS_LABEL.test("e2e-42-abcd1234")).toBe(true);
    expect(DNS_LABEL.test("a")).toBe(true);
    expect(DNS_LABEL.test("-leading")).toBe(false);
    expect(DNS_LABEL.test("trailing-")).toBe(false);
    expect(DNS_LABEL.test("Upper")).toBe(false);
    expect(DNS_LABEL.test("has.dot")).toBe(false);
    expect(DNS_LABEL.test("")).toBe(false);
  });
});

describe("projectSlug", () => {
  it("is a valid single DNS label carrying the run id", () => {
    const slug = projectSlug({ runId: "1234567890", dir: "/tmp/e2e-abc" });
    expect(DNS_LABEL.test(slug)).toBe(true);
    expect(slug).toMatch(/^e2e-1234567890-[0-9a-f]{8}$/);
  });

  it("is stable for the same inputs, and moves when the directory does", () => {
    const a = projectSlug({ runId: "1", dir: "/tmp/one" });
    const b = projectSlug({ runId: "1", dir: "/tmp/one" });
    const c = projectSlug({ runId: "1", dir: "/tmp/two" });
    expect(a).toBe(b);
    expect(a).not.toBe(c);
  });

  it("falls back to a fixed local token when no run id is given", () => {
    expect(projectSlug({ dir: "/tmp/x" })).toMatch(/^e2e-local-[0-9a-f]{8}$/);
  });

  it("never exceeds MAX_SLUG_LEN, however long the run id is", () => {
    const slug = projectSlug({ runId: "x".repeat(200), dir: "/tmp/x" });
    expect(slug.length).toBeLessThanOrEqual(52);
    expect(DNS_LABEL.test(slug)).toBe(true);
  });
});

describe("renderOcelConfig", () => {
  const config = renderOcelConfig({
    slug: "e2e-42-abcd1234",
    previewDomain: "*.e2e.example.com",
    apps: [{ name: "app", path: ".", framework: "next" }],
  });

  it("carries the project slug, provider and preview wildcard", () => {
    expect(config).toContain(`slug: "e2e-42-abcd1234"`);
    expect(config).toContain("awsProvider()");
    expect(config).toContain(`preview: "*.e2e.example.com"`);
  });

  it("renders each apps entry verbatim, in the given key order", () => {
    expect(config).toContain(`apps: [{ name: "app", path: ".", framework: "next" }]`);
  });

  it("omits the domains block when no preview domain is given", () => {
    expect(renderOcelConfig({ slug: "s", apps: [] })).not.toContain("domains:");
  });

  it("is pure: the same arguments render byte-for-byte the same file", () => {
    const args = { slug: "s", apps: [{ name: "app", path: ".", framework: "express" }] };
    expect(renderOcelConfig(args)).toBe(renderOcelConfig(args));
  });

  // Pinned so the generated-file marker cannot silently drift to something
  // inaccurate again — see this function's own doc comment: it used to claim
  // scripts/e2e-next/deploy.mjs wrote every rendered config, which stopped
  // being true the moment scripts/e2e-node started calling this too.
  it("names itself as an e2e harness output, not a single script's", () => {
    expect(config).toContain("// Generated by an ocel e2e harness (scripts/e2e-next or scripts/e2e-node). Do not edit.");
  });
});

