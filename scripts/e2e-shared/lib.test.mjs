// This module is the single source of truth both scripts/e2e-next and
// scripts/e2e-node build their assertions on — the bytecode-cache key
// derivation is what has to mirror cloud/aws/deploy/bytecode.go and
// cloud/aws/cmd/lambdanode/bootstrap/bytecode.go exactly, on both sides, for
// any assertion built on it to mean anything. Before scripts/e2e-node existed
// this was covered only transitively through scripts/e2e-next/lib.test.mjs;
// this file tests it directly, at the layer both harnesses actually depend
