func TestGenerate_LeavesEveryStartingShapeParseable(t *testing.T) {
	for name, source := range map[string]string{
		"empty":              "{}\n",
		"no compilerOptions": "{\n  \"include\": [\"**/*.ts\"]\n}\n",
		"empty paths":        "{\n  \"compilerOptions\": {\n    \"paths\": {}\n  }\n}\n",
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			write(t, filepath.Join(dir, "tsconfig.json"), source)

			if err := Generate([]App{{Dir: dir, Variables: []manifestbuilder.Variable{clientVar("PUBLIC_SITE_URL", "https://example.com")}}}); err != nil {
				t.Fatalf("Generate: %v", err)
			}

			updated := read(t, filepath.Join(dir, "tsconfig.json"))
			var parsed struct {
				CompilerOptions struct {
					Paths map[string][]string `json:"paths"`
				} `json:"compilerOptions"`
			}
			if err := json.Unmarshal([]byte(updated), &parsed); err != nil {
				t.Fatalf("tsconfig is no longer parseable (%v):\n%s", err, updated)
			}
			want, err := accessorTarget("")
			if err != nil {
				t.Fatal(err)
			}
			if got := parsed.CompilerOptions.Paths[specifier]; len(got) != 1 || got[0] != want {
				t.Errorf("paths[%q] = %v, want [%q]\n%s", specifier, got, want, updated)
			}
		})
	}
}

func TestGenerate_TwiceLeavesTheSameFiles(t *testing.T) {
	dir := appDir(t)
	apps := []App{{Dir: dir, Variables: []manifestbuilder.Variable{clientVar("PUBLIC_SITE_URL", "https://example.com")}}}

	if err := Generate(apps); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	first := read(t, filepath.Join(dir, "tsconfig.json"))
	accessor := read(t, filepath.Join(dir, ".ocel", "env-client.ts"))

	if err := Generate(apps); err != nil {
		t.Fatalf("Generate again: %v", err)
	}
	if got := read(t, filepath.Join(dir, "tsconfig.json")); got != first {
		t.Errorf("tsconfig changed on a second run:\n%s\nwant\n%s", got, first)
	}
	if got := read(t, filepath.Join(dir, ".ocel", "env-client.ts")); got != accessor {
		t.Errorf("accessor changed on a second run:\n%s", got)
	}
}

func TestGenerate_LeavesAProjectWithNoClientValuesAlone(t *testing.T) {
	dir := appDir(t)
	before := read(t, filepath.Join(dir, "tsconfig.json"))

	if err := Generate([]App{{Dir: dir, Variables: []manifestbuilder.Variable{serverVar("STRIPE_API_KEY", "sk-live")}}}); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	if _, err := os.Stat(filepath.Join(dir, ".ocel", "env-client.ts")); !os.IsNotExist(err) {
		t.Errorf("an accessor was generated for a project with no client-accessible value (err = %v)", err)
	}
	if got := read(t, filepath.Join(dir, "tsconfig.json")); got != before {
		t.Errorf("tsconfig was edited:\n%s", got)
	}
}

