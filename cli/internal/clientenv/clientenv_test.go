func clientVar(key, value string) manifestbuilder.Variable {
	return manifestbuilder.Variable{
		Key:              key,
		Class:            resourcesv1.VariableClass_VARIABLE_CLASS_PLAIN,
		Value:            value,
		ClientAccessible: true,
	}
}

func serverVar(key, value string) manifestbuilder.Variable {
	return manifestbuilder.Variable{
		Key:   key,
		Class: resourcesv1.VariableClass_VARIABLE_CLASS_SENSITIVE,
		Value: value,
	}
}

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func appDir(t *testing.T) string {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "tsconfig.json"), "{\n  \"compilerOptions\": {\n    \"strict\": true\n  },\n  \"include\": [\"**/*.ts\"]\n}\n")
	return dir
}

func TestGenerate_WritesTheAccessorTheSDKPins(t *testing.T) {
	dir := appDir(t)

	if err := Generate([]App{{Dir: dir, Variables: []manifestbuilder.Variable{clientVar("NEXT_PUBLIC_SITE_URL", "https://example.com")}}}); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	want := "// Generated by ocel. Do not edit.\n" +
		"const inlined = (key: string, value: string | undefined): string => {\n" +
		"  if (value !== undefined) return value;\n" +
		"  const error = new Error(\n" +
		"    \"'\" + key + \"' is client-accessible, but no value was inlined into this bundle. A bundler inlines only the names matching its own public convention (NEXT_PUBLIC_* under Next, VITE_* under Vite); rename the variable to one of those, or read it on the server instead.\"\n" +
		"  );\n" +
		"  error.name = \"EnvClientError\";\n" +
		"  throw error;\n" +
		"};\n" +
		"\n" +
		"export const clientEnv = {\n" +
		"  NEXT_PUBLIC_SITE_URL: inlined(\"NEXT_PUBLIC_SITE_URL\", process.env.NEXT_PUBLIC_SITE_URL),\n" +
		"};\n"
	if got := read(t, filepath.Join(dir, ".ocel", "env-client.ts")); got != want {
		t.Errorf("accessor =\n%q\nwant\n%q", got, want)
	}
}

func TestGenerate_ReadsEachKeyUnderItsDeclaredName(t *testing.T) {
	dir := appDir(t)

	err := Generate([]App{{Dir: dir, Variables: []manifestbuilder.Variable{
		clientVar("NEXT_PUBLIC_APP_ID", "app_1"),
		clientVar("VITE_APP_ID", "app_2"),
	}}})
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}

	accessor := read(t, filepath.Join(dir, ".ocel", "env-client.ts"))
	for _, want := range []string{"process.env.NEXT_PUBLIC_APP_ID", "process.env.VITE_APP_ID"} {
		if !strings.Contains(accessor, want) {
			t.Errorf("accessor =\n%s\nwant a read of %s", accessor, want)
		}
	}
	if strings.Contains(accessor, "NEXT_PUBLIC_VITE_APP_ID") {
		t.Errorf("accessor =\n%s\nwant no prefix added to a declared name", accessor)
	}
}

