package cli

import (
	"encoding/json"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"strings"

	"github.com/ocelhq/ocel/cli/internal/projectconfig"
	"github.com/ocelhq/ocel/pkg/naming"
	bindingsv1 "github.com/ocelhq/ocel/pkg/proto/common/bindings/v1"
	envvarsv1 "github.com/ocelhq/ocel/pkg/proto/provider/envvars/v1"
)

const bindingTypesFileName = "ocel-bindings.d.ts"

const transformsModule = "@ocel/transforms"

const customBindingKey = "custom"

var tsIdentifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func renderBindingTypes(coordinate string, bound []projectconfig.Binding, published []*envvarsv1.BindingSummary) string {
	module := tsString(transformsModule)
	var b strings.Builder
	fmt.Fprintf(&b, "// generated by `ocel bindings generate` from %s; do not edit\n", coordinate)
	fmt.Fprintf(&b, "import %s;\n\n", module)
	fmt.Fprintf(&b, "declare module %s {\n", module)
	b.WriteString("  interface BindingsGenerated {\n    generated: true;\n  }\n\n")
	b.WriteString("  interface Bindings {\n")

	readable := readableBindings(bound, published)
	for _, kind := range slices.Sorted(maps.Keys(readable)) {
		fmt.Fprintf(&b, "    %s: {\n", tsKey(kind))
		named := readable[kind]
		for _, name := range slices.Sorted(maps.Keys(named)) {
			fmt.Fprintf(&b, "      %s: %s;\n", tsKey(name), tsProperties(named[name]))
		}
		b.WriteString("    };\n")
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

func readableBindings(bound []projectconfig.Binding, published []*envvarsv1.BindingSummary) map[string]map[string][]*envvarsv1.PropertyShape {
	declared := make(map[string][]projectconfig.Binding, len(bound))
	for _, binding := range bound {
		declared[binding.External] = append(declared[binding.External], binding)
	}
	out := map[string]map[string][]*envvarsv1.PropertyShape{}
	put := func(kind, name string, shapes []*envvarsv1.PropertyShape) {
		if out[kind] == nil {
			out[kind] = map[string][]*envvarsv1.PropertyShape{}
		}
		out[kind][name] = shapes
	}
	for _, record := range published {
		keyed := declared[record.GetName()]
		if len(keyed) == 0 {
			if record.GetType() == bindingsv1.BindingType_BINDING_TYPE_CUSTOM {
				put(customBindingKey, record.GetName(), record.GetProperties())
			}
			continue
		}
		for _, binding := range keyed {
			put(naming.ResourceTypeName(binding.Type), binding.Name, record.GetProperties())
		}
	}
	return out
}

func tsProperties(shapes []*envvarsv1.PropertyShape) string {
	if len(shapes) == 0 {
		return "{}"
	}
	out := make([]string, 0, len(shapes))
	for _, shape := range shapes {
		out = append(out, fmt.Sprintf("%s: %s", tsKey(shape.GetName()), tsType(shape)))
	}
	return "{ " + strings.Join(out, "; ") + " }"
}

func tsType(shape *envvarsv1.PropertyShape) string {
	scalar := "unknown"
	switch shape.GetJsonType() {
	case naming.JSONTypeString, naming.JSONTypeNumber, naming.JSONTypeBoolean:
		scalar = shape.GetJsonType()
	case naming.JSONTypeObject:
		scalar = "Record<string, unknown>"
	}
	if shape.GetList() {
		return scalar + "[]"
	}
	return scalar
}

func tsKey(name string) string {
	if tsIdentifier.MatchString(name) {
		return name
	}
	return tsString(name)
}

func tsString(value string) string {
	quoted, _ := json.Marshal(value)
	return string(quoted)
}
