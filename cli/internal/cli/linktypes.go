package cli

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"github.com/ocelhq/ocel/pkg/naming"
	envv1 "github.com/ocelhq/ocel/pkg/proto/env/v1"
)

const linkTypesFileName = "ocel-links.d.ts"

var tsIdentifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func renderLinkTypes(providerPackage, coordinate string, links []*envv1.LinkSummary) string {
	transformModule := tsString(providerPackage + "/transform")
	var b strings.Builder
	fmt.Fprintf(&b, "// generated by `ocel link generate` from %s; do not edit\n", coordinate)
	fmt.Fprintf(&b, "import %s;\n\n", transformModule)
	fmt.Fprintf(&b, "declare module %s {\n", transformModule)
	b.WriteString("  interface LinksGenerated {\n    generated: true;\n  }\n\n")
	b.WriteString("  interface Links {\n")
	for _, link := range links {
		fmt.Fprintf(&b, "    %s: %s;\n", tsKey(link.GetName()), tsProperties(link.GetProperties()))
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

func tsProperties(shapes []*envv1.PropertyShape) string {
	if len(shapes) == 0 {
		return "{}"
	}
	out := make([]string, 0, len(shapes))
	for _, shape := range shapes {
		out = append(out, fmt.Sprintf("%s: %s", tsKey(shape.GetName()), tsType(shape)))
	}
	return "{ " + strings.Join(out, "; ") + " }"
}

func tsType(shape *envv1.PropertyShape) string {
	scalar := "unknown"
	switch shape.GetJsonType() {
	case naming.JSONTypeString, naming.JSONTypeNumber, naming.JSONTypeBoolean:
		scalar = shape.GetJsonType()
	case naming.JSONTypeObject:
		scalar = "Record<string, unknown>"
	}
	if shape.GetList() {
		return scalar + "[]"
	}
	return scalar
}

func tsKey(name string) string {
	if tsIdentifier.MatchString(name) {
		return name
	}
	return tsString(name)
}

func tsString(value string) string {
	quoted, _ := json.Marshal(value)
	return string(quoted)
}
