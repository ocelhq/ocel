package realtimetypes

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/ocelhq/ocel/cli/internal/declaration"
	resourcesv1 "github.com/ocelhq/ocel/pkg/proto/app/resources/v1"
)

const FileName = "ocel-realtime.d.ts"

const header = "// Generated by ocel from the realtime resources this project declares. Do not edit.\n"

var tsIdentifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func Generate(dir string, resources []declaration.Resource) (bool, error) {
	path := filepath.Join(dir, FileName)
	if !slices.ContainsFunc(resources, isRealtime) {
		return false, removeGenerated(path)
	}
	content, err := Render(resources)
	if err != nil {
		return false, err
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return false, fmt.Errorf("write %s: %w", path, err)
	}
	return true, nil
}

func removeGenerated(path string) error {
	current, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if !bytes.HasPrefix(current, []byte(header)) {
		return nil
	}
	if err := os.Remove(path); err != nil {
		return fmt.Errorf("remove %s, which no realtime resource needs: %w", path, err)
	}
	return nil
}

func isRealtime(r declaration.Resource) bool {
	return r.Type == resourcesv1.ResourceType_RESOURCE_TYPE_REALTIME && r.Realtime != nil
}

func Render(resources []declaration.Resource) (string, error) {
	realtime := slices.Clone(resources)
	realtime = slices.DeleteFunc(realtime, func(r declaration.Resource) bool { return !isRealtime(r) })
	slices.SortStableFunc(realtime, func(a, b declaration.Resource) int { return strings.Compare(a.Name, b.Name) })

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("// Type a browser client with one: createRealtimeClient<RealtimeResources[\"name\"]>({ url }).\n\n")
	b.WriteString("export type RealtimeResources = {\n")
	for _, resource := range realtime {
		fmt.Fprintf(&b, "  %s: {\n", jsonLiteral(resource.Name))
		for _, channel := range resource.Realtime.GetChannels() {
			event, err := renderSchema(channel.GetSchema())
			if err != nil {
				return "", fmt.Errorf("channel %q of realtime %q has a schema that is not JSON: %w", channel.GetPattern(), resource.Name, err)
			}
			members := []string{"event: " + event}
			if channel.GetPublish() == resourcesv1.RealtimePublish_REALTIME_PUBLISH_RULE {
				members = append(members, "publish: "+event)
			}
			if channel.GetWildcard() {
				members = append(members, "wildcard: true")
			}
			fmt.Fprintf(&b, "    %s: { %s };\n", jsonLiteral(channel.GetPattern()), strings.Join(members, "; "))
		}
		b.WriteString("  };\n")
	}
	b.WriteString("};\n")
	return b.String(), nil
}

func renderSchema(written string) (string, error) {
	if strings.TrimSpace(written) == "" {
		return "unknown", nil
	}
	var root any
	if err := json.Unmarshal([]byte(written), &root); err != nil {
		return "", err
	}
	r := schemaRenderer{root: root, resolving: map[string]bool{}}
	return r.render(root), nil
}

type schemaRenderer struct {
	root      any
	resolving map[string]bool
}

func (r schemaRenderer) render(schema any) string {
	switch s := schema.(type) {
	case bool:
		if s {
			return "unknown"
		}
		return "never"
	case map[string]any:
		return r.renderObjectSchema(s)
	}
	return "unknown"
}

func (r schemaRenderer) renderObjectSchema(s map[string]any) string {
	if ref, ok := s["$ref"].(string); ok {
		return r.renderReference(ref)
	}
	if value, ok := s["const"]; ok {
		return jsonLiteral(value)
	}
	if values, ok := s["enum"].([]any); ok {
		literals := make([]string, 0, len(values))
		for _, value := range values {
			literals = append(literals, jsonLiteral(value))
		}
		return joinTypes(literals, " | ")
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if members, ok := s[key].([]any); ok {
			return r.renderEach(members, " | ")
		}
	}
	if members, ok := s["allOf"].([]any); ok {
		return r.renderEach(members, " & ")
	}
	switch t := s["type"].(type) {
	case string:
		return r.renderTyped(t, s)
	case []any:
		types := make([]string, 0, len(t))
		for _, one := range t {
			if name, ok := one.(string); ok {
				types = append(types, r.renderTyped(name, s))
			}
		}
		return joinTypes(types, " | ")
	}
	if _, ok := s["properties"]; ok {
		return r.renderTyped("object", s)
	}
	return "unknown"
}

func (r schemaRenderer) renderEach(members []any, separator string) string {
	types := make([]string, 0, len(members))
	for _, member := range members {
		types = append(types, r.render(member))
	}
	return joinTypes(types, separator)
}

func (r schemaRenderer) renderReference(ref string) string {
	if r.resolving[ref] {
		return "unknown"
	}
	target, ok := r.resolvePointer(ref)
	if !ok {
		return "unknown"
	}
	r.resolving[ref] = true
	defer delete(r.resolving, ref)
	return r.render(target)
}

func (r schemaRenderer) resolvePointer(ref string) (any, bool) {
	pointer, isLocal := strings.CutPrefix(ref, "#")
	if !isLocal {
		return nil, false
	}
	node := r.root
	for _, token := range strings.Split(strings.TrimPrefix(pointer, "/"), "/") {
		if token == "" {
			continue
		}
		token = strings.ReplaceAll(strings.ReplaceAll(token, "~1", "/"), "~0", "~")
		object, ok := node.(map[string]any)
		if !ok {
			return nil, false
		}
		if node, ok = object[token]; !ok {
			return nil, false
		}
	}
	return node, true
}

func (r schemaRenderer) renderTyped(name string, s map[string]any) string {
	switch name {
	case "string", "boolean", "null":
		return name
	case "integer", "number":
		return "number"
	case "array":
		return r.renderArray(s)
	case "object":
		return r.renderObject(s)
	}
	return "unknown"
}

func (r schemaRenderer) renderArray(s map[string]any) string {
	if prefix, ok := s["prefixItems"].([]any); ok {
		elements := make([]string, 0, len(prefix)+1)
		for _, item := range prefix {
			elements = append(elements, r.render(item))
		}
		if items, hasItems := s["items"]; hasItems && items != false {
			elements = append(elements, "..."+parenthesize(r.render(items))+"[]")
		}
		return "[" + strings.Join(elements, ", ") + "]"
	}
	items, ok := s["items"]
	if !ok {
		return "unknown[]"
	}
	return parenthesize(r.render(items)) + "[]"
}

func (r schemaRenderer) renderObject(s map[string]any) string {
	properties, _ := s["properties"].(map[string]any)
	additional, hasAdditional := s["additionalProperties"]
	if len(properties) == 0 {
		if hasAdditional && additional != false && additional != true {
			return "Record<string, " + r.render(additional) + ">"
		}
		return "Record<string, unknown>"
	}
	required := map[string]bool{}
	if names, ok := s["required"].([]any); ok {
		for _, name := range names {
			if text, ok := name.(string); ok {
				required[text] = true
			}
		}
	}
	names := make([]string, 0, len(properties))
	for name := range properties {
		names = append(names, name)
	}
	slices.Sort(names)
	members := make([]string, 0, len(names)+1)
	for _, name := range names {
		optional := "?"
		if required[name] {
			optional = ""
		}
		members = append(members, tsKey(name)+optional+": "+r.render(properties[name]))
	}
	if hasAdditional && additional != false {
		members = append(members, "[key: string]: unknown")
	}
	return "{ " + strings.Join(members, "; ") + " }"
}

func jsonLiteral(value any) string {
	var b bytes.Buffer
	encoder := json.NewEncoder(&b)
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		return "unknown"
	}
	return strings.TrimSuffix(b.String(), "\n")
}

func joinTypes(types []string, separator string) string {
	if len(types) == 0 {
		return "never"
	}
	if len(types) == 1 {
		return types[0]
	}
	operands := make([]string, 0, len(types))
	for _, t := range types {
		operands = append(operands, parenthesize(t))
	}
	return strings.Join(operands, separator)
}

func parenthesize(t string) string {
	depth := 0
	for _, c := range t {
		switch c {
		case '{', '[', '(', '<':
			depth++
		case '}', ']', ')', '>':
			depth--
		case '|', '&':
			if depth == 0 {
				return "(" + t + ")"
			}
		}
	}
	return t
}

func tsKey(name string) string {
	if tsIdentifier.MatchString(name) {
		return name
	}
	return jsonLiteral(name)
}
